package engine

import "testing"

// PositionLegal 单测：拦"走子方能一步吃到对方将/帅"的引擎不安全局面。
// 背景：皮卡鱼收到这类局面直接退出进程（CRITICAL ERROR: King can be captured），
// PC 端引擎反复崩溃重启（2026-10-01 残局实测：识别列偏把不照面的车/将拼到同列）。
// 坐标约定：FEN 首行 y=0（黑方底线），红方在 y=9；每行必须恰 9 格。

func TestPositionLegal(t *testing.T) {
	cases := []struct {
		name string
		fen  string
		want bool
	}{
		{"合法开局", "rnbakabnr/9/1c5c1/p1p1p1p1p/9/9/P1P1P1P1P/1C5C1/9/RNBAKABNR w - - 0 1", true},
		{"合法残局_车将不同列", "4kab2/4a4/9/9/9/9/9/9/9/3K5 w - - 0 1", true},
		// 红车 (4,4) 与黑将 (4,0) 同列中间全空，红走即可吃将
		{"红车直瞄黑将", "4k4/9/9/9/4R4/9/9/9/9/3K5 w - - 0 1", false},
		// 同上但中间 (4,1) 有黑士遮挡（仕中宫点位）
		{"车将同列有挡子_合法", "4k4/4a4/9/9/4R4/9/9/9/9/3K5 w - - 0 1", true},
		// 红炮 (4,9) 与黑将 (4,0) 间恰好一个炮架 R(4,6)。注意：本盘红帅 (6,9)
		// 出九宫，PositionLegal 实际先被区域校验拦截（want=false 仍成立）；
		// 炮攻击路径由下方"黑炮隔一子打帅_黑走"用例干净覆盖
		{"红炮隔一子打将", "4k4/9/9/9/9/9/4R4/9/9/4C1K2 w - - 0 1", false},
		// 炮与将之间两个黑卒（第一子为炮架、第二子非炮）打不到
		//（原用黑士做炮架，但士在 (4,6)/(4,7) 出九宫，违反区域规则校验；
		//  红帅用 3KC4 布局保证其在九宫内——原 4C1K2 的帅在 x=6 出九宫）
		{"红炮隔两子打不到_合法", "4k4/9/9/9/9/9/4p4/4p4/9/3KC4 w - - 0 1", true},
		// 黑炮 (4,5) 与红帅 (4,9) 间恰好一个炮架 r(4,7)
		{"黑炮隔一子打帅_黑走", "4k4/9/9/9/9/4c4/9/4r4/9/4K4 b - - 0 1", false},
		// 红马 (3,2) 攻黑将 (4,0)：主轴 y，马腿 (3,1) 空
		{"红马攻将", "4k4/9/3N5/9/9/9/9/9/9/3K5 w - - 0 1", false},
		// 同上但腿位 (3,1) 被黑卒蹩住（不能用黑士：(3,1) 非仕点位，会被点位
		// 白名单拦截混淆"蹩腿"语义）
		{"红马蹩腿攻不到_合法", "4k4/3p5/3N5/9/9/9/9/9/9/3K5 w - - 0 1", true},
		{"将帅对脸_恒非法", "4k4/9/9/9/9/9/9/9/9/4K4 w - - 0 1", false},
		{"缺黑将", "9/9/9/9/9/9/9/9/9/4K4 w - - 0 1", false},
		// 过河红兵 (4,1) 正攻上方黑将 (4,0)
		{"过河红兵正攻将", "4k4/4P4/9/9/9/9/9/9/9/3K5 w - - 0 1", false},
		// 过河红兵 (3,0) 侧攻同行黑将 (4,0)
		{"过河红兵侧攻将", "3Pk4/9/9/9/9/9/9/9/9/3K5 w - - 0 1", false},
		// 红兵 (4,5) 未过河（y=5>4），正攻/侧攻都够不到黑将
		{"未过河红兵攻不到_合法", "4k4/9/9/9/9/4P4/9/9/9/3K5 w - - 0 1", true},
		// 黑卒 (4,8) 正攻下方红帅 (4,9)
		{"过河黑卒攻帅_黑走", "4k4/9/9/9/9/9/9/9/4p4/4K4 b - - 0 1", false},
		// 黑车 (4,8) 直瞄红帅 (4,9)，轮黑走
		{"黑车直瞄红帅_黑走", "4k4/9/9/9/9/9/9/9/4r4/4K4 b - - 0 1", false},
		// 黑马 (3,7) 攻红帅 (4,9)：主轴 y，马腿 (3,8) 空（黑方攻击方小写对称用例）
		{"黑马攻帅_黑走", "3k5/9/9/9/9/9/9/3n5/9/4K4 b - - 0 1", false},
		// 同上但腿位 (3,8) 被红卒蹩住（同前：红仕点位白名单放不下 (3,8)）
		{"黑马蹩腿攻不到_合法", "3k5/9/9/9/9/9/9/3n5/3P5/4K4 b - - 0 1", true},
		// 黑车 (4,7) 直瞄红帅被红仕 (4,8) 挡住；黑卒正攻位 (4,8) 也被仕占
		{"黑车直瞄被红仕挡住_合法", "3k5/9/9/9/9/9/9/4r4/4A4/4K4 b - - 0 1", true},
		// 区域规则（皮卡鱼对三类同样报 Unsupported position 立即退出，第二轮审查实测）：
		// 黑将 (2,0) 出黑方九宫（报告复现 FEN：黑马在红方九宫属马不受限，皮卡鱼只报黑王非法）
		{"黑将出九宫", "2k6/9/9/9/9/9/9/9/4n4/3K1R3 b - - 0 1", false},
		// 黑仕 (4,5) 出九宫；同列将帅间有仕遮挡，不构成照面，拒绝仅因仕位
		{"黑仕出九宫", "4k4/9/9/9/9/4a4/9/9/9/4K4 b - - 0 1", false},
		// 红相 (0,1) 过河（y<5）
		{"红相过河", "3k5/B8/9/9/9/9/9/9/9/4K4 w - - 0 1", false},
		// 红帅 (3,6) 出红方九宫（与黑将不同列，拒绝仅因帅位）
		{"红帅出九宫", "4k4/9/9/9/9/9/3K5/9/9/9 w - - 0 1", false},
		// 2026-10-01 真实事故盘面：识别列偏把红车与黑将拼到同列（照面校验放行、引擎崩）
		{"事故盘面_车将同列", "6b2/5k3/9/4C3p/p3C1b2/N4R2P/9/9/4A4/3AK4 w - - 0 1", false},
		// 仕/相点位白名单（2026-10-27 补刀）：旧校验对仕相只查九宫/不过河，
		// "半场内但不在点位"穿透直达皮卡鱼 → CRITICAL ERROR 退出，半天实战四炸。
		// 两条真实崩溃盘面取自当天 cabinet.log（BLACK/WHITE bishop(s) on invalid positions）
		{"黑象半场内非点位_真实四炸盘面", "5k3/4a4/5a2b/p7p/7b1/R5P2/4P3P/B7c/3rr4/2BK5 w - - 0 1", false},
		{"红相半场内非点位_真实四炸盘面", "3akab2/3c5/4b4/8p/P8/P1B5P/3nB4/4p4/9/4K4 w - - 0 1", false},
		// 田字点位上的黑象（4,2）合法，不得误伤
		{"黑象田字点位_合法", "4k4/9/4b4/9/9/9/9/9/9/4K4 w - - 0 1", true},
		// 红仕 (3,8) 在九宫内但非宫斜点位（row1 只认 x=4）——识别造不出这种局面，必为误识别
		{"红仕九宫内非点位", "3k5/9/9/9/9/9/9/9/4K4/3A4 w - - 0 1", false},
	}
	for _, tc := range cases {
		if got := PositionLegal(tc.fen); got != tc.want {
			t.Errorf("%s: PositionLegal = %v, 期望 %v\n  fen: %s", tc.name, got, tc.want, tc.fen)
		}
	}
}
